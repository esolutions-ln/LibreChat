"""Synthetic twin generation.

Privacy rules (docs/nmb/ANALYSIS.md): sensitive/identifier/text columns become fake tokens that are checked
against the real values; rare categories fold into "other"; numeric and datetime ranges use the 1st-99th
percentile; no output row may reproduce a real row when a continuous column is part of it.
"""
from __future__ import annotations

import os
import re

import numpy as np
import pandas as pd

TOKEN_KINDS = {"identifier", "text"}
_ROW_ATTEMPTS = 6


class SynthesisError(ValueError):
    pass


def _norm(v) -> str:
    if v is None or (isinstance(v, float) and np.isnan(v)) or v is pd.NaT or v is pd.NA:
        return ""
    s = str(v).strip()
    try:
        return repr(round(float(s), 4))
    except ValueError:
        return s.lower()


def _tokens(name: str, n: int, rng, forbid: set[str]) -> pd.Series:
    prefix = re.sub(r"[^A-Za-z0-9]", "", name).upper()[:8] or "VAL"
    nums = (rng.permutation(900_000)[:n] + 100_000).tolist()
    toks = []
    for x in nums:
        t = f"{prefix}-{x}"
        while t in forbid:
            t = f"{prefix}-X{int(rng.integers(10**6, 10**7))}"
        toks.append(t)
    return pd.Series(toks, dtype=object)


def _with_nulls(values: pd.Series, frac: float, rng) -> pd.Series:
    if frac <= 0:
        return values
    mask = rng.random(len(values)) < frac
    out = values.astype(object).where(~mask, None)
    return out


def _numeric(real: pd.Series, kind: str, n: int, rng) -> pd.Series:
    x = real.dropna().astype(float)
    if x.empty:
        return pd.Series([None] * n, dtype=object)
    lo, hi = float(x.quantile(0.01)), float(x.quantile(0.99))
    c = x.clip(lo, hi)
    sd = float(c.std(ddof=0))
    v = rng.normal(float(c.mean()), sd, n) if sd > 0 else np.full(n, float(c.mean()))
    v = np.clip(v, lo, hi)
    if kind == "integer":
        return pd.Series(np.rint(v).astype("int64"), dtype=object)
    dec = 2 if np.allclose(x, x.round(2)) else 4
    return pd.Series(np.round(v, dec), dtype=object)


def _datetime(real: pd.Series, n: int, rng) -> pd.Series:
    x = real.dropna()
    if x.empty:
        return pd.Series([None] * n, dtype=object)
    ns = x.astype("int64")
    lo, hi = int(ns.quantile(0.01)), int(ns.quantile(0.99))
    draw = pd.to_datetime(rng.integers(lo, max(hi, lo) + 1, n))
    if bool((x.dt.normalize() == x).all()):
        return pd.Series(draw.strftime("%Y-%m-%d"), dtype=object)
    return pd.Series(draw.strftime("%Y-%m-%d %H:%M:%S"), dtype=object)


def _category(real: pd.Series, kind: str, n: int, rng, min_count: int) -> pd.Series:
    counts = real.dropna().astype(str).value_counts()
    if counts.empty:
        return pd.Series([None] * n, dtype=object)
    if kind != "boolean":
        keep = counts[counts >= min_count]
        folded = int(counts[counts < min_count].sum())
        counts = keep.copy()
        if folded:
            counts["other"] = counts.get("other", 0) + folded
    p = (counts / counts.sum()).to_numpy()
    return pd.Series(rng.choice(counts.index.to_numpy(dtype=object), n, p=p), dtype=object)


def _column(name: str, meta: dict, real: pd.Series, n: int, rng, min_count: int, forbid: set[str]) -> pd.Series:
    kind = meta["kind"]
    if meta["sensitive"] or kind in TOKEN_KINDS:
        return _tokens(name, n, rng, forbid)
    if kind in ("numeric", "integer"):
        col = _numeric(real, kind, n, rng)
    elif kind == "datetime":
        col = _datetime(real, n, rng)
    else:
        col = _category(real, kind, n, rng, min_count)
    return _with_nulls(col, float(meta.get("null_fraction", 0)), rng)


def _builtin(typed: pd.DataFrame, cols: dict[str, dict], selected: list[str], n: int, seed, min_count: int,
             forbid: dict[str, set[str]]) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    return pd.DataFrame({c: _column(c, cols[c], typed[c], n, rng, min_count, forbid.get(c, set()))
                         for c in selected})


def _sdv(typed: pd.DataFrame, cols: dict[str, dict], selected: list[str], n: int, seed, min_count: int,
         forbid: dict[str, set[str]]) -> pd.DataFrame | None:
    """GaussianCopula over the non-token columns; token columns are still generated by us."""
    try:
        from sdv.single_table import GaussianCopulaSynthesizer
        try:
            from sdv.metadata import Metadata
            detect = Metadata.detect_from_dataframe
        except ImportError:  # older SDV
            from sdv.metadata import SingleTableMetadata
            detect = lambda d: (lambda m: (m.detect_from_dataframe(d), m)[1])(SingleTableMetadata())  # noqa: E731
        modelled = [c for c in selected if not (cols[c]["sensitive"] or cols[c]["kind"] in TOKEN_KINDS)]
        rng = np.random.default_rng(seed)
        out = pd.DataFrame(index=range(n))
        if modelled:
            if seed is not None:
                np.random.seed(seed)
            frame = typed[modelled].copy()
            synth = GaussianCopulaSynthesizer(detect(frame))
            synth.fit(frame)
            sample = synth.sample(n).reset_index(drop=True)
            for c in modelled:
                col = sample[c]
                if cols[c]["kind"] in ("numeric", "integer"):
                    x = typed[c].dropna()
                    col = col.clip(x.quantile(0.01), x.quantile(0.99))
                    col = col.round().astype("int64") if cols[c]["kind"] == "integer" else col.round(4)
                elif cols[c]["kind"] == "datetime":
                    col = pd.to_datetime(col).dt.strftime("%Y-%m-%d %H:%M:%S")
                elif cols[c]["kind"] == "categorical":
                    rare = typed[c].value_counts()
                    rare = set(rare[rare < min_count].index)
                    col = col.where(~col.isin(rare), "other")
                out[c] = col
        for c in selected:
            if c not in out:
                out[c] = _tokens(c, n, rng, forbid.get(c, set()))
        return out[selected]
    except Exception:
        return None


def synthesize(raw: pd.DataFrame, typed: pd.DataFrame, columns: list[dict], selected: list[str], rows: int,
               seed: int | None = None, engine: str = "builtin", min_count: int = 5) -> tuple[pd.DataFrame, str]:
    cols = {c["name"]: c for c in columns}
    forbid = {c: set(raw[c].dropna().astype(str)) for c in selected
              if cols[c]["sensitive"] or cols[c]["kind"] in TOKEN_KINDS}
    engine = os.environ.get("NMB_SYNTH_ENGINE", engine)
    check_rows = any(cols[c]["kind"] in ("numeric", "datetime") for c in selected)
    real_rows = ({tuple(_norm(v) for v in r) for r in raw[selected].itertuples(index=False, name=None)}
                 if check_rows else set())
    used = "builtin"
    for attempt in range(_ROW_ATTEMPTS):
        s = None if seed is None else seed + attempt
        out = None
        if engine == "sdv":
            out = _sdv(typed, cols, selected, rows + 20, s, min_count, forbid)
        if out is not None:
            used = "sdv"
        else:
            used = "builtin"
            out = _builtin(typed, cols, selected, rows + 20, s, min_count, forbid)
        if check_rows:
            keep = [tuple(_norm(v) for v in r) not in real_rows for r in out.itertuples(index=False, name=None)]
            out = out[keep]
        if len(out) >= rows:
            out = out.head(rows).reset_index(drop=True)
            for c, real_vals in forbid.items():
                if real_vals & set(out[c].dropna().astype(str)):
                    raise SynthesisError("synthetic_leak")
            return out, used
    raise SynthesisError("synthetic_collision")
